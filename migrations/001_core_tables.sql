-- SCG-35: the tables the app uses today (PostgreSQL).
-- Applied once by smartcash/database/postgres.py; recorded in schema_migrations.
-- Money = NUMERIC (exact), dates = DATE, every table with user data has user_id.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL CHECK (length(username) BETWEEN 3 AND 30),
    password_hash TEXT NOT NULL,                 -- scrypt hash, never the password
    failed_logins INTEGER NOT NULL DEFAULT 0,
    locked_until  TIMESTAMP,                     -- set after too many wrong passwords
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- "Sokha" and "sokha" are the same account.
CREATE UNIQUE INDEX users_username_lower ON users (lower(username));

CREATE TABLE transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT REFERENCES users(id) ON DELETE CASCADE,
    tx_date        DATE NOT NULL,
    tx_type        TEXT NOT NULL CHECK (tx_type IN ('expense', 'income')),
    amount         NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    currency       TEXT NOT NULL CHECK (currency IN ('USD', 'KHR')),
    category       TEXT NOT NULL,
    payment_method TEXT NOT NULL,
    note           TEXT NOT NULL DEFAULT '',
    is_demo        SMALLINT NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX transactions_user_date ON transactions (user_id, tx_date);

CREATE TABLE exchange_rates (
    rate_date   DATE PRIMARY KEY,
    khr_per_usd NUMERIC(10, 2) NOT NULL CHECK (khr_per_usd > 0),
    source      TEXT NOT NULL,
    is_filled   SMALLINT NOT NULL DEFAULT 0 CHECK (is_filled IN (0, 1))
);
